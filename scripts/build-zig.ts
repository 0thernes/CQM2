#!/usr/bin/env bun
/**
 * Compiles Zig 0.17.0 kernels to BOTH:
 *   1. Portable WebAssembly SIMD128 (`cqm2_zig.wasm`) -> embedded into `src/native/zig-wasm-embedded.ts`
 *   2. Native Workstation Shared Library (`native/bin/cqm2_zig.dll` / `.so` / `.dylib`)
 */
import { existsSync, mkdirSync, readFileSync, copyFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const ZIG_DIR = join(ROOT, 'zig');
const BIN_DIR = join(ROOT, 'native', 'bin');
const EMBED_OUT = join(ROOT, 'src', 'native', 'zig-wasm-embedded.ts');

function findZigBinary(): string | null {
  if (Bun.which('zig')) return Bun.which('zig')!;
  const wingetBase = join(process.env.LOCALAPPDATA ?? '', 'Microsoft', 'WinGet', 'Packages');
  if (existsSync(wingetBase)) {
    for (const dir of readdirSync(wingetBase)) {
      if (dir.startsWith('zig.zig')) {
        const sub = join(wingetBase, dir);
        for (const inner of readdirSync(sub)) {
          const candidate = join(sub, inner, process.platform === 'win32' ? 'zig.exe' : 'zig');
          if (existsSync(candidate)) return candidate;
        }
      }
    }
  }
  return null;
}

const zigExe = findZigBinary();
if (!zigExe) {
  if (existsSync(EMBED_OUT)) {
    console.log('[build:zig] Zig compiler not on PATH; keeping existing pre-compiled WASM embed.');
    process.exit(0);
  }
  console.error('[build:zig] Zig compiler not found and no prebuilt WASM embed present.');
  process.exit(1);
}

console.log(`[build:zig] Using Zig: ${zigExe}`);
const testProc = Bun.spawnSync([zigExe, 'build', 'test'], { cwd: ZIG_DIR, stdout: 'inherit', stderr: 'inherit' });
if (testProc.exitCode !== 0) {
  console.error('[build:zig] Zig unit tests failed!');
  process.exit(testProc.exitCode);
}

const buildProc = Bun.spawnSync([zigExe, 'build', '--release=fast'], { cwd: ZIG_DIR, stdout: 'inherit', stderr: 'inherit' });
if (buildProc.exitCode !== 0) {
  console.error('[build:zig] Zig release build failed!');
  process.exit(buildProc.exitCode);
}

const wasmPath = join(ZIG_DIR, 'zig-out', 'bin', 'cqm2_zig.wasm');
if (!existsSync(wasmPath)) {
  console.error(`[build:zig] Expected WASM output missing at ${wasmPath}`);
  process.exit(1);
}

const wasmBytes = readFileSync(wasmPath);
const base64 = wasmBytes.toString('base64');

mkdirSync(join(ROOT, 'src', 'native'), { recursive: true });
writeFileSync(
  EMBED_OUT,
  `// AUTO-GENERATED by scripts/build-zig.ts — DO NOT EDIT MANUALLY\n` +
    `// Compiled from zig/src/root.zig (wasm32-freestanding +simd128 +bulk_memory, ${wasmBytes.byteLength} bytes)\n` +
    `export const CQM2_ZIG_WASM_BYTE_LENGTH = ${wasmBytes.byteLength};\n` +
    `export const CQM2_ZIG_WASM_BASE64 = '${base64}';\n`,
  'utf8',
);

mkdirSync(BIN_DIR, { recursive: true });
for (const name of ['cqm2_zig.dll', 'libcqm2_zig.so', 'libcqm2_zig.dylib']) {
  const p = join(ZIG_DIR, 'zig-out', 'bin', name);
  const pLib = join(ZIG_DIR, 'zig-out', 'lib', name);
  const src = existsSync(p) ? p : existsSync(pLib) ? pLib : null;
  if (src) {
    const dst = join(BIN_DIR, name);
    try {
      copyFileSync(src, dst);
    } catch (err) {
      const code = (err as NodeJS.ErrnoException)?.code;
      if (code === 'EBUSY' && existsSync(dst)) {
        console.warn(`[build:zig] ${name} is currently mapped by a running process; keeping loaded native/bin/${name}.`);
      } else {
        throw err;
      }
    }
  }
}

console.log(`[build:zig] Embedded cqm2_zig.wasm (${wasmBytes.byteLength} bytes) + copied native library to native/bin/.`);
