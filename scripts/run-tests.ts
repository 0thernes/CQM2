#!/usr/bin/env bun
/**
 * CQM2 Automated Test & Coverage Gate (`bun run test`).
 * Runs `bun test --coverage --coverage-reporter=lcov`, parses exact line coverage across `src/`
 * (excluding DOM-only Three.js canvas bindings that run in headless/browser), enforces `>= 85.0%`
 * line coverage, and writes Shields.io endpoint badge `docs/badges/coverage.json` (`repo-check.mjs` item 13)!
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const COV_DIR = join(ROOT, 'coverage');
const BADGE_DIR = join(ROOT, 'docs', 'badges');
mkdirSync(COV_DIR, { recursive: true });
mkdirSync(BADGE_DIR, { recursive: true });

const res = Bun.spawnSync(
  [process.execPath, 'test', '--coverage', '--coverage-reporter=text', '--coverage-reporter=lcov', `--coverage-dir=${COV_DIR}`],
  {
    cwd: ROOT,
    stdout: 'inherit',
    stderr: 'inherit',
  },
);

if (res.exitCode !== 0) {
  process.exit(res.exitCode);
}

const lcovPath = join(COV_DIR, 'lcov.info');
if (!existsSync(lcovPath)) {
  console.error('[test] Expected coverage/lcov.info was not generated by bun test');
  process.exit(1);
}

const lcovText = readFileSync(lcovPath, 'utf8');
let totalLinesFound = 0;
let totalLinesHit = 0;
let currentFile = '';

for (const rawLine of lcovText.split(/\r?\n/)) {
  const line = rawLine.trim();
  if (line.startsWith('SF:')) {
    currentFile = line.slice(3).replace(/\\/g, '/');
  } else if (line.startsWith('LF:')) {
    if (
      currentFile.includes('src/') &&
      !currentFile.endsWith('zig-wasm-embedded.ts') &&
      !currentFile.includes('src/ui/') &&
      !currentFile.includes('src/render/')
    ) {
      totalLinesFound += Number(line.slice(3));
    }
  } else if (line.startsWith('LH:')) {
    if (
      currentFile.includes('src/') &&
      !currentFile.endsWith('zig-wasm-embedded.ts') &&
      !currentFile.includes('src/ui/') &&
      !currentFile.includes('src/render/')
    ) {
      totalLinesHit += Number(line.slice(3));
    }
  }
}

const pct = totalLinesFound > 0 ? (totalLinesHit / totalLinesFound) * 100.0 : 0.0;
const pctFormatted = `${pct.toFixed(1)}%`;

const badgePayload = {
  schemaVersion: 1,
  label: 'coverage',
  message: pctFormatted,
  color: pct >= 90 ? 'brightgreen' : pct >= 85 ? 'green' : 'yellow',
};

if (process.env.CI !== 'true') {
  writeFileSync(join(BADGE_DIR, 'coverage.json'), JSON.stringify(badgePayload, null, 2) + '\n');
  console.log(`[test] Line coverage across tested src/ modules: ${totalLinesHit}/${totalLinesFound} (${pctFormatted}) -> wrote docs/badges/coverage.json`);
} else {
  console.log(`[test] Line coverage across tested src/ modules: ${totalLinesHit}/${totalLinesFound} (${pctFormatted}) [CI read-only verify]`);
}

if (pct < 85.0) {
  console.error(`[test] Coverage gate failed: ${pctFormatted} < 85.0% minimum threshold`);
  process.exit(1);
}
